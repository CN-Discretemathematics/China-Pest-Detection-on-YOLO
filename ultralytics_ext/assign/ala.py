# --------------------------------------------------------------------------- #
# 配置
# --------------------------------------------------------------------------- #
@dataclass
class ALAConfig:
    """ALA 超参。

    Attributes
    ----------
    enabled:
        总开关。关闭时 ``ala_core`` 原样返回，保证可做 A/B 对照。
    beta_thr:
        判定"非忽略粘连"的阈值。取 0.05 —— 与 Pest24 论文定义 nontrivial
        adhesion 的口径完全一致（论文：4657 张图 β>0.05）。
    q_min:
        每个 GT 的最小正样本数。低于此值视为"被饿死"。
    max_reassign_ratio:
        单个支配者最多可被回收的 anchor 比例（防止把支配者掏空）。
    min_iou:
        回收 anchor 与目标 GT 的最小 IoU（过低的 anchor 送过去是噪声）。
    enable_quota:
        ALA-2 配额补偿（改分配，不改 loss）。
    enable_soft:
        ALA-1 软共享。仅在 loss 侧支持权重缩放时启用；本模块在
        ``ala_core`` 中以"权重表"的形式给出，供上层 loss 使用。
    """

    enabled: bool = True
    beta_thr: float = 0.05
    q_min: int = 3
    max_reassign_ratio: float = 0.5
    min_iou: float = 0.05
    enable_quota: bool = True
    enable_soft: bool = False

    def describe(self) -> str:
        return (
            f"ALA(enabled={self.enabled}, beta_thr={self.beta_thr}, q_min={self.q_min}, "
            f"quota={self.enable_quota}, soft={self.enable_soft})"
        )


# --------------------------------------------------------------------------- #
# 几何工具（纯 Python，xyxy 绝对坐标）
# --------------------------------------------------------------------------- #
Box = Tuple[float, float, float, float]


def box_area(b: Box) -> float:
    """闭区间矩形面积。"""
    w = max(0.0, b[2] - b[0])
    h = max(0.0, b[3] - b[1])
    return w * h


def intersection_area(a: Box, b: Box) -> float:
    """两矩形交集面积。"""
    ix1 = max(a[0], b[0])
    iy1 = max(a[1], b[1])
    ix2 = min(a[2], b[2])
    iy2 = min(a[3], b[3])
    if ix2 <= ix1 or iy2 <= iy1:
        return 0.0
    return (ix2 - ix1) * (iy2 - iy1)


def iou(a: Box, b: Box) -> float:
    """标准 IoU。"""
    inter = intersection_area(a, b)
    if inter <= 0.0:
        return 0.0
    union = box_area(a) + box_area(b) - inter
    return inter / union if union > 0.0 else 0.0


def adhesion_coefficient(a: Box, b: Box) -> float:
    """Pest24 论文定义的粘连系数 β = |A∩B| / |A∪B|。

    ⚠️ 注意：该式与 IoU **数值等价**（同一公式）。论文称之为"粘连系数"是因为
    它在捕捉板场景下度量的是"两虫物理黏连"而非"框是否重复"—— 语义不同，数值相同。
    这里保留独立的函数名与文档说明，以对齐原论文的术语体系。
    """
    inter = intersection_area(a, b)
    if inter <= 0.0:
        return 0.0
    union = box_area(a) + box_area(b) - inter
    return inter / union if union > 0.0 else 0.0


def adhesion_matrix(gt_boxes: Sequence[Box]) -> List[List[float]]:
    """GT 两两粘连度矩阵 β。"""
    n = len(gt_boxes)
    m = [[0.0] * n for _ in range(n)]
    for i in range(n):
        for j in range(i + 1, n):
            b = adhesion_coefficient(gt_boxes[i], gt_boxes[j])
            m[i][j] = b
            m[j][i] = b
    return m


def build_clusters(beta: Sequence[Sequence[float]], thr: float) -> List[List[int]]:
    """按粘连度阈值构建连通簇（并查集）。"""
    n = len(beta)
    parent = list(range(n))

    def find(x: int) -> int:
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    def union(x: int, y: int) -> None:
        rx, ry = find(x), find(y)
        if rx != ry:
            parent[ry] = rx

    for i in range(n):
        for j in range(i + 1, n):
            if beta[i][j] > thr:
                union(i, j)

    groups: Dict[int, List[int]] = {}
    for i in range(n):
        groups.setdefault(find(i), []).append(i)
    return [sorted(g) for g in groups.values() if len(g) > 1]



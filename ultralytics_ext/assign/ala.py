"""ADEA · I1 · ALA —— 粘连感知标签分配 (Adhesion-aware Label Assignment)

出处 / 出处依据
--------------
回应 EP-YOLO (Sensors 2026, 26(9):2607) §4.3 第 3 点：

    "the similar morphologies of densely packed pests not only trigger visual
     feature aliasing but also cause bounding boxes generated by the
     Non-Maximum Suppression (NMS) algorithm to suffer from erroneous
     suppression or spatial drift in highly occluded regions, thereby
     compromising counting accuracy."

以及 §4.2 Fig.12b 的失败案例：

    "266 个目标中漏了 10 个 ... This dense case inevitably triggers the
     Non-Maximum Suppression (NMS) mechanism during post-processing, which
     could filter out valid targets as redundant predictions incorrectly."

机制假说 M1
-----------
Ultralytics 的 TaskAlignedAssigner 对每个 GT 取 top-k 个 anchor 作为正样本，
随后用 ``target_gt_idx = mask_pos.argmax(-2)`` 在 GT 维度取最大值 ——
**每个 anchor 只能属于一个 GT**。当两个 GT 高度粘连 (β 大) 且都很小时，
它们的候选 anchor 集合几乎完全重合，于是绝大多数正样本 anchor 被 argmax
独占分配给其中一个 GT，另一个 GT 只保留极少数"严格更优"的 anchor；
同时每 GT 的 top-k 名额被前者挤占 → 该实例**正样本被系统性饿死**。

本模块的修复
------------
在不破坏"每个 anchor 至多一个 GT"这一 Ultralytics 不变式的前提下，
把被"饿死"实例的 anchor 从粘连簇内的支配者手里**回收**给它：

    ALA-2（配额补偿）：n_i < q_min 的 GT 放宽配额，从簇内支配者回收 anchor。

设计要点
--------
* **纯算法层无第三方依赖**：``ala_core`` 只用标准库，可独立单测；
  ``apply_ala`` 是 torch 适配层。
* **对普通场景零行为改变**：不处于粘连簇 (β <= beta_thr) 的 GT 完全不参与
  回收流程；未启用时 (``enabled=False``) 直接返回原分配。
* **不修改 loss**：保持"anchor → 单一 GT"不变式，因此可与未打补丁的
  ``vflLoss`` 直接配合（降级路径 §5.2）。

粘连度定义沿用 Pest24 原论文（Wang et al., 2020, DOI 10.1016/j.compag.2020.105585）::

    beta(A, B) = |A ∩ B| / |A ∪ B|

⚠️ **重要更正（由自测发现）**：该式与 IoU **在数值上完全等价**（分子分母相同）。
原论文的"粘连度"与"交并比"是**同一公式**，差别只在**语义**：
IoU 在检测中通常被解释为"两个框是否指向同一个物体"（重复检测信号），
而论文把它解释为"两只虫在捕捉板上物理黏连的程度"（粘连信号）。
本项目沿用论文的 β 记号与阈值（0.05 = 论文的"nontrivial adhesion"），
但在论述中必须说清这一点，**不得**声称 β 与 IoU 在数值上有区别。
"""


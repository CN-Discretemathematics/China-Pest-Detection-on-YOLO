# 核心算法（纯 Python）
# --------------------------------------------------------------------------- #
@dataclass
class ALAStats:
    """一次 ALA 调用的统计量（用于冒烟测试 P6 与诊断）。"""

    n_gt: int = 0
    n_anchors: int = 0
    n_positive_before: int = 0
    n_positive_after: int = 0
    n_clusters: int = 0
    n_starved_gt: int = 0
    n_reassigned: int = 0
    starved_before: List[int] = field(default_factory=list)
    starved_after: List[int] = field(default_factory=list)

    def as_dict(self) -> Dict[str, object]:
        return {
            "n_gt": self.n_gt,
            "n_anchors": self.n_anchors,
            "n_positive_before": self.n_positive_before,
            "n_positive_after": self.n_positive_after,
            "n_clusters": self.n_clusters,
            "n_starved_gt": self.n_starved_gt,
            "n_reassigned": self.n_reassigned,
            "starved_before": self.starved_before,
            "starved_after": self.starved_after,
        }


def _gt_positive_counts(target_gt_idx: Sequence[int], n_gt: int, fg_mask: Optional[Sequence[bool]] = None) -> List[int]:
    """每个 GT 实际分到的正样本数。

    ⚠️ ``fg_mask`` 的必要性（ultralytics 8.4.x）
    --------------------------------------------
    8.4.x 的 ``select_highest_overlaps`` 返回的 ``target_gt_idx`` 对**背景 anchor 也填 0**
    （不是 8.3.x 的 -1）。若不按 ``fg_mask`` 过滤，GT0 的计数会变成"全部 anchor 数"，
    配额补偿随之失效（实测：ALA 无法救回被饿死的实例）。
    """
    counts = [0] * n_gt
    for k, t in enumerate(target_gt_idx):
        if fg_mask is not None and not fg_mask[k]:
            continue
        if t is not None and t >= 0:
            counts[t] += 1
    return counts


def ala_core(
    target_gt_idx: Sequence[int],
    anchors: Sequence[Box],
    gt_boxes: Sequence[Box],
    cfg: ALAConfig,
    stats: ALAStats | None = None,
    per_gt_qmin: Sequence[int] | None = None,
    overlaps: Optional[Sequence[Sequence[float]]] = None,
    fg_mask: Optional[Sequence[bool]] = None,
) -> Tuple[List[int], ALAStats]:
    """粘连感知配额补偿（ALA-2）。

    Parameters
    ----------
    target_gt_idx:
        每个 anchor 归属的 GT 下标；``-1`` 表示背景（Ultralytics 约定）。
        长度必须等于 ``len(anchors)``。
    anchors:
        所有 anchor 的 xyxy 框。
    gt_boxes:
        所有 GT 的 xyxy 框。
    cfg:
        :class:`ALAConfig`。
    per_gt_qmin:
        可选的**逐 GT 最小正样本数**（长度须等于 GT 数）。
        用于 I2 DLA 的密度调制：拥挤区域的 GT 获得更高配额。
        ``None`` 时统一使用 ``cfg.q_min``。

    Returns
    -------
    (new_target_gt_idx, stats)
        新的分配（保持"anchor 至多一个 GT"不变式）与统计量。
    """
    new_idx = list(target_gt_idx)
    n_gt = len(gt_boxes)
    n_anchor = len(anchors) if anchors else (len(overlaps[0]) if overlaps else 0)
    st = stats if stats is not None else ALAStats()
    st.n_gt = n_gt
    st.n_anchors = n_anchor
    counts_before = _gt_positive_counts(new_idx, n_gt, fg_mask)
    st.n_positive_before = sum(counts_before)

    if per_gt_qmin is None:
        qmin_list = [cfg.q_min] * n_gt
    else:
        if len(per_gt_qmin) != n_gt:
            raise ValueError(
                f"per_gt_qmin length {len(per_gt_qmin)} != n_gt {n_gt}"
            )
        qmin_list = [max(0, int(q)) for q in per_gt_qmin]

    if not cfg.enabled or not cfg.enable_quota or n_gt < 2 or n_anchor == 0:
        st.n_positive_after = st.n_positive_before
        st.starved_before = [i for i, c in enumerate(counts_before) if c < qmin_list[i]]
        st.starved_after = list(st.starved_before)
        return new_idx, st

    beta = adhesion_matrix(gt_boxes)
    clusters = build_clusters(beta, cfg.beta_thr)
    st.n_clusters = len(clusters)

    for cluster in clusters:
        # 簇内每个 GT 的粘连邻居平均 β（用于配额放宽系数）
        neigh_beta: Dict[int, float] = {}
        for i in cluster:
            vals = [beta[i][j] for j in cluster if j != i]
            neigh_beta[i] = sum(vals) / len(vals) if vals else 0.0

        for starved in cluster:
            q_min_here = qmin_list[starved]
            if counts_before[starved] >= q_min_here:
                continue
            need = q_min_here - counts_before[starved]
            st.n_starved_gt += 1

            # 候选供体：簇内其他 GT 拥有的 anchor，且与 starved GT 有足够重叠
            donors = [d for d in cluster if d != starved]
            if not donors:
                continue

            cand: List[Tuple[float, int]] = []  # (overlap_with_starved, anchor_idx)
            for ai in range(n_anchor):
                if fg_mask is not None and not fg_mask[ai]:
                    continue  # 只动正样本 anchor（背景 anchor 不得被"回收"）
                if new_idx[ai] not in donors:
                    continue
                if overlaps is not None:
                    ov = float(overlaps[starved][ai])
                else:
                    ov = iou(anchors[ai], gt_boxes[starved])
                if ov >= cfg.min_iou:
                    cand.append((ov, ai))
            if not cand:
                continue
            # 供体可让出量：每个供体保留至少 q_min 个正样本
            donor_capacity: Dict[int, int] = {}
            for d in donors:
                donor_capacity[d] = max(0, counts_before[d] - qmin_list[d])
                donor_capacity[d] = min(
                    donor_capacity[d],
                    int(counts_before[d] * cfg.max_reassign_ratio),
                )

            cand.sort(key=lambda t: (-t[0], t[1]))
            taken = 0
            for ov, ai in cand:
                if taken >= need:
                    break
                donor = new_idx[ai]
                if donor_capacity.get(donor, 0) <= 0:
                    continue
                donor_capacity[donor] -= 1
                new_idx[ai] = starved
                taken += 1
                st.n_reassigned += 1

    counts_after = _gt_positive_counts(new_idx, n_gt)
    st.n_positive_after = sum(counts_after)
    st.starved_before = [i for i, c in enumerate(counts_before) if c < qmin_list[i]]
    st.starved_after = [i for i, c in enumerate(counts_after) if c < qmin_list[i]]
    return new_idx, st


# --------------------------------------------------------------------------- #
# torch 适配层
# --------------------------------------------------------------------------- #
def _xywh_to_xyxy(boxes) -> List[Box]:
    """torch/numpy 的 (cx, cy, w, h) → (x1, y1, x2, y2)，逐元素转 float。"""
    out: List[Box] = []
    for b in boxes:
        cx, cy, w, h = (float(b[0]), float(b[1]), float(b[2]), float(b[3]))
        out.append((cx - w / 2.0, cy - h / 2.0, cx + w / 2.0, cy + h / 2.0))
    return out


def apply_ala(
    target_gt_idx,
    anchors_xywh,
    gt_boxes_xywh,
    cfg: ALAConfig,
    stats=None,
    per_gt_qmin=None,
):
    """torch 适配层：对 assigner 的输出做 ALA 配额补偿。

    Parameters
    ----------
    target_gt_idx:
        ``torch.Tensor``，形状 (num_anchors,)，dtype long。
    anchors_xywh:
        ``torch.Tensor``，形状 (num_anchors, 4)，xywh。
    gt_boxes_xywh:
        ``torch.Tensor``，形状 (num_gt, 4)，xywh。
    cfg:
        :class:`ALAConfig`。
    per_gt_qmin:
        可选逐 GT 配额（供 I2 DLA 传入密度调制后的配额）。

    Returns
    -------
    (target_gt_idx_new, stats)
        新分配张量与统计量。输入张量不会被原地修改。
    """
    import torch  # 延迟导入：纯算法层不依赖 torch

    idx_list = [int(v) for v in target_gt_idx.detach().cpu().tolist()]
    anchors = _xywh_to_xyxy(anchors_xywh.detach().cpu().tolist())
    gts = _xywh_to_xyxy(gt_boxes_xywh.detach().cpu().tolist())

    qmin = None
    if per_gt_qmin is not None:
        qmin = [int(q) for q in per_gt_qmin]

    new_list, st = ala_core(idx_list, anchors, gts, cfg, stats, per_gt_qmin=qmin)

    new_tensor = target_gt_idx.clone()
    changed = [i for i, (a, b) in enumerate(zip(idx_list, new_list)) if a != b]
    if changed:
        idx = torch.tensor(changed, dtype=torch.long, device=target_gt_idx.device)
        vals = torch.tensor(
            [new_list[i] for i in changed], dtype=target_gt_idx.dtype, device=target_gt_idx.device
        )
        new_tensor[idx] = vals
    return new_tensor, st


# --------------------------------------------------------------------------- #
# 适配 ultralytics 8.4.x 的 TaskAlignedAssigner（forward / select_highest_overlaps）
# --------------------------------------------------------------------------- #
def apply_ala_assign(
    target_gt_idx,
    fg_mask,
    gt_bboxes,
    overlaps,
    mask_gt,
    cfg: ALAConfig,
    per_gt_qmin=None,
    stats=None,
):
    """在 **ultralytics 8.4.x 的 assigner 张量约定**下施加 ALA 配额补偿。

    与 8.3.x 的差异
    --------------
    8.4.x 的 ``TaskAlignedAssigner`` 重构为 ``nnModule.forward()``，
    独占分配发生在 ``select_highest_overlaps``（"Anchors assigned to multiple
    gt_bboxes keep the highest overlap"）—— 这正是 M1 描述的"饿死"机制。
    分配器内部已经算好 GT×anchor 的 IoU 矩阵 ``overlaps``，
    本函数直接复用它，无需自行构造 anchor 框。

    Parameters
    ----------
    target_gt_idx:
        (b, num_anchors) 每个 anchor 归属的 GT 下标（-1 为背景）。
    fg_mask:
        (b, num_anchors) bool，正样本掩码。
    gt_bboxes:
        (b, n_max_boxes, 4) GT 框（xyxy，像素）。
    overlaps:
        (b, n_max_boxes, num_anchors) GT×anchor 的 IoU。
    mask_gt:
        (b, n_max_boxes, 1) 有效 GT 掩码。
    cfg:
        :class:`ALAConfig`。
    per_gt_qmin:
        可选逐 GT 配额（供 I2 DLA 传入密度调制后的配额）。
        ⚠️ **按 batch 组织**：``per_gt_qmin[b]`` 是第 b 个 batch 元素的逐 GT 配额 list
        （早期版本误传成扁平的 list，导致 ``int(list)`` 抛异常、补丁被静默回退）。

    Returns
    -------
    (target_gt_idx_new, fg_mask, stats)
    """
    import torch

    if not cfg.enabled or not cfg.enable_quota:
        return target_gt_idx, fg_mask, (stats if stats is not None else ALAStats())

    device = target_gt_idx.device
    new_tgi = target_gt_idx.clone()
    total = ALAStats()

    tgi_cpu = target_gt_idx.detach().cpu()
    fg_cpu = fg_mask.detach().cpu()
    gtb_cpu = gt_bboxes.detach().cpu()
    ovl_cpu = overlaps.detach().cpu()
    mask_cpu = mask_gt.detach().cpu() if mask_gt is not None else None

    for b in range(tgi_cpu.shape[0]):
        tgi_b = tgi_cpu[b]
        fg_b = fg_cpu[b]
        n_max = gtb_cpu.shape[1]

        if mask_cpu is not None:
            valid = mask_cpu[b].reshape(-1).bool()
            n_gt = int(valid.sum())
        else:
            n_gt = int(tgi_b.max().item()) + 1 if tgi_b.numel() else 0
            valid = torch.arange(n_max) < n_gt
        if n_gt < 2:
            continue

        gtb = gtb_cpu[b][:n_gt]
        ovl = ovl_cpu[b][:n_gt]

        idx_list = [int(v) for v in tgi_b.tolist()]
        ovl_list = [[float(v) for v in row] for row in ovl.tolist()]

        # 逐 batch 取出该 batch 的逐 GT 配额
        qmin = None
        if per_gt_qmin is not None:
            if b < len(per_gt_qmin):
                qmin = [int(q) for q in per_gt_qmin[b]]

        new_list, st = ala_core(
            idx_list,
            [],
            gtb.tolist(),
            cfg,
            None,
            per_gt_qmin=qmin,
            overlaps=ovl_list,
            fg_mask=fg_b.tolist(),
        )

        # 写回（只改动被回收的 anchor）
        changed = [i for i, (a, c) in enumerate(zip(idx_list, new_list)) if a != c]
        if changed:
            dev_idx = torch.tensor(changed, dtype=torch.long, device=device)
            dev_vals = torch.tensor(
                [new_list[i] for i in changed], dtype=new_tgi.dtype, device=device
            )
            new_tgi[b, dev_idx] = dev_vals

        total.n_gt += st.n_gt
        total.n_anchors += st.n_anchors
        total.n_positive_before += st.n_positive_before
        total.n_positive_after += st.n_positive_after
        total.n_clusters += st.n_clusters
        total.n_starved_gt += st.n_starved_gt
        total.n_reassigned += st.n_reassigned
        total.starved_before += st.starved_before
        total.starved_after += st.starved_after

    return new_tgi, fg_mask, total
